-- ============================================================================
-- V1: catalog schema (categories, classification attributes, products, variants)
-- ============================================================================

-- ----------------------------------------------------------------------------
-- category: tree of categories (self-reference through parent_id)
-- ----------------------------------------------------------------------------
create table category (
    id          bigint       generated by default as identity,
    code        varchar(50)  not null,
    name        varchar(255) not null,
    parent_id   bigint,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),

    constraint pk_category        primary key (id),
    constraint uk_category_code   unique (code),
    constraint fk_category_parent foreign key (parent_id) references category (id)
);

create index idx_category_parent on category (parent_id);

-- ----------------------------------------------------------------------------
-- attribute: dictionary of classification attributes (voltage, color, size...)
-- ----------------------------------------------------------------------------
create table attribute (
    id          bigint       generated by default as identity,
    code        varchar(50)  not null,
    name        varchar(255) not null,
    data_type   varchar(10)  not null,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),

    constraint pk_attribute           primary key (id),
    constraint uk_attribute_code      unique (code),
    constraint ck_attribute_data_type check (data_type in ('TEXT', 'NUMBER', 'BOOLEAN'))
);

-- ----------------------------------------------------------------------------
-- category_attribute: which attributes each category requires/shows
-- ----------------------------------------------------------------------------
create table category_attribute (
    category_id  bigint  not null,
    attribute_id bigint  not null,
    mandatory    boolean not null default false,
    visible      boolean not null default true,

    constraint pk_category_attribute           primary key (category_id, attribute_id),
    constraint fk_category_attribute_category  foreign key (category_id)  references category (id) on delete cascade,
    constraint fk_category_attribute_attribute foreign key (attribute_id) references attribute (id)
);

-- the primary key already covers searches by category_id
create index idx_category_attribute_attribute on category_attribute (attribute_id);

-- ----------------------------------------------------------------------------
-- product: base product, common to all its variants
-- ----------------------------------------------------------------------------
create table product (
    id          bigint       generated by default as identity,
    code        varchar(50)  not null,
    name        varchar(255) not null,
    description text,
    category_id bigint       not null,
    active      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),

    constraint pk_product          primary key (id),
    constraint uk_product_code     unique (code),
    constraint fk_product_category foreign key (category_id) references category (id)
);

create index idx_product_category on product (category_id);

-- ----------------------------------------------------------------------------
-- product_attribute_value: attributes shared by all variants (e.g. screen size)
-- ----------------------------------------------------------------------------
create table product_attribute_value (
    id            bigint        generated by default as identity,
    product_id    bigint        not null,
    attribute_id  bigint        not null,
    value_text    text,
    value_number  numeric(15,4),
    value_boolean boolean,

    constraint pk_product_attribute_value primary key (id),
    constraint uk_pav_product_attribute   unique (product_id, attribute_id),
    constraint fk_pav_product             foreign key (product_id)   references product (id) on delete cascade,
    constraint fk_pav_attribute           foreign key (attribute_id) references attribute (id),
    constraint ck_pav_one_value           check (num_nonnulls(value_text, value_number, value_boolean) = 1)
);

-- the unique constraint already covers searches by product_id
create index idx_pav_attribute on product_attribute_value (attribute_id);

-- ----------------------------------------------------------------------------
-- product_variant: the sellable SKU (stock, price and cart point here)
-- ----------------------------------------------------------------------------
create table product_variant (
    id          bigint      generated by default as identity,
    code        varchar(50) not null,
    product_id  bigint      not null,
    active      boolean     not null default true,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),

    constraint pk_product_variant         primary key (id),
    constraint uk_product_variant_code    unique (code),
    constraint fk_product_variant_product foreign key (product_id) references product (id)
);

create index idx_product_variant_product on product_variant (product_id);

-- ----------------------------------------------------------------------------
-- variant_attribute_value: attributes that define each variant (e.g. voltage)
-- ----------------------------------------------------------------------------
create table variant_attribute_value (
    id            bigint        generated by default as identity,
    variant_id    bigint        not null,
    attribute_id  bigint        not null,
    value_text    text,
    value_number  numeric(15,4),
    value_boolean boolean,

    constraint pk_variant_attribute_value primary key (id),
    constraint uk_vav_variant_attribute   unique (variant_id, attribute_id),
    constraint fk_vav_variant             foreign key (variant_id)   references product_variant (id) on delete cascade,
    constraint fk_vav_attribute           foreign key (attribute_id) references attribute (id),
    constraint ck_vav_one_value           check (num_nonnulls(value_text, value_number, value_boolean) = 1)
);

-- the unique constraint already covers searches by variant_id
create index idx_vav_attribute on variant_attribute_value (attribute_id);
